export function AddBlock({ onInsert, existingTypes = [] }) {
  const [open, setOpen] = useState(false);
  const ref = useRef(null);
  useOutside(ref, open, () => setOpen(false));

  return (
    <div ref={ref} className="ow">
      <div className="ow-add">
        <span className="ow-add-line" />
        <button type="button" className="ow-add-btn" aria-expanded={open} onClick={() => setOpen(o => !o)}>
          <RepIcon name="plus" size={18} />Add block
        </button>
        <span className="ow-add-line" />
      </div>
      {open && (
        <div className="ow-picker">
          <div className="ow-picker-head">
            <b>Add a block</b>
            <button type="button" className="ow-iconbtn" onClick={() => setOpen(false)} aria-label="Close"><RepIcon name="close" size={18} /></button>
          </div>
          {BLOCK_TYPES.map(group => (
            <div className="ow-picker-group" key={group.category}>
              <span className="ow-picker-cat">{group.category}</span>
              {group.items.map(item => {
                const taken = item.single && existingTypes.includes(item.type);
                const disabled = group.locked || taken;
                return (
                  <button key={item.type} type="button" className="ow-pick" disabled={disabled}
                    onClick={() => { onInsert({ id: generateId(), type: item.type, data: {}, visible: true }); setOpen(false); }}>
                    <span className="ow-pick-icon"><RepIcon name={item.icon} size={20} /></span>
                    <span className="ow-pick-text">
                      <b>{item.label}{group.locked && <span className="ow-soon">SOON</span>}</b>
                      <span>{taken ? 'Already on your page' : item.desc}</span>
                    </span>
                  </button>
                );
              })}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}

