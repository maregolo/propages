export function LiveToast({ slug, onDismiss }) {
  const url = `${SITE_URL}/${slug}`;
  const [copied, copy] = useCopy(url);
  return (
    <div className="ow ow-toast" role="status">
      <span className="ow-welcome-icon" aria-hidden="true"><RepIcon name="check" size={22} strokeWidth={2.5} /></span>
      <span className="ow-toast-text"><b>Your page is live</b><span>{DOMAIN}/{slug}</span></span>
      <button type="button" className="ow-btn ow-btn--primary" onClick={copy}>{copied ? 'Copied' : 'Copy link'}</button>
      <button type="button" className="ow-iconbtn" onClick={onDismiss} aria-label="Dismiss"><RepIcon name="close" size={18} /></button>
    </div>
  );
}

export function WelcomeBanner({ slug, onDismiss, onEdit }) {
  function dismiss() {
    try { localStorage.setItem(`pp_welcomed_${slug}`, 'true'); } catch { /* private mode */ }
    onDismiss();
  }
  return (
    <div className="ow ow-welcome">
      <span className="ow-welcome-icon" aria-hidden="true"><RepIcon name="edit" size={20} /></span>
      <div style={{ flex: 1 }}>
        <b>This is your page. Make it yours.</b>
        <p>The words below are suggestions for your industry. Swap in your own, then add real reviews and proof numbers. Those stay hidden from visitors until you do.</p>
        {onEdit && <button type="button" className="ow-textbtn" onClick={() => { onEdit(); dismiss(); }} style={{ color: 'var(--site-mint)' }}>Start editing<RepIcon name="arrowRight" size={16} /></button>}
      </div>
      <button type="button" className="ow-iconbtn" onClick={dismiss} aria-label="Dismiss"><RepIcon name="close" size={18} /></button>
    </div>
  );
}
