function useOutside(ref, open, onClose) {
  useEffect(() => {
    if (!open) return;
    function handle(e) { if (ref.current && !ref.current.contains(e.target)) onClose(); }
    function key(e) { if (e.key === 'Escape') onClose(); }
    document.addEventListener('mousedown', handle);
    document.addEventListener('touchstart', handle);
    document.addEventListener('keydown', key);
    return () => {
      document.removeEventListener('mousedown', handle);
      document.removeEventListener('touchstart', handle);
      document.removeEventListener('keydown', key);
    };
  }, [ref, open, onClose]);
}

function useCopy(text) {
  const [copied, setCopied] = useState(false);
  function copy() {
    navigator.clipboard?.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }).catch(() => {});
  }
  return [copied, copy];
}

// ── Share panel: link + scannable QR ─────────────────────────────────────────

function SharePanel({ slug }) {
  const url = `${SITE_URL}/${slug}`;
  const [svg, setSvg] = useState('');
  const [copied, copy] = useCopy(url);
  const canShare = typeof navigator !== 'undefined' && !!navigator.share;

  useEffect(() => {
    let live = true;
    import('qrcode').then(QR => QR.toString(url, { type: 'svg', margin: 0, errorCorrectionLevel: 'M', color: { dark: '#0D1117', light: '#FFFFFF' } }))
      .then(s => { if (live) setSvg(s); })
      .catch(() => {});
    return () => { live = false; };
  }, [url]);

  async function download() {
    const QR = await import('qrcode');
    const data = await QR.toDataURL(url, { width: 1200, margin: 2, errorCorrectionLevel: 'M', color: { dark: '#0D1117', light: '#FFFFFF' } });
    const a = document.createElement('a');
    a.href = data;
    a.download = `propages-${slug}-qr.png`;
    document.body.appendChild(a);
    a.click();
    a.remove();
  }

  return (
    <div className="ow-panel">
      <h2 className="ow-panel-title">Share your page</h2>
      {/* Generated by the qrcode library from our own URL. */}
      <div className="ow-qr" role="img" aria-label={`QR code for ${DOMAIN}/${slug}`} dangerouslySetInnerHTML={{ __html: svg }} />
      <span className="ow-hint" style={{ textAlign: 'center' }}>Print it on leave-behinds and door hangers. Scans open your page.</span>
      <div className="ow-url"><RepIcon name="link" size={18} />{DOMAIN}/{slug}</div>
      <div className="ow-actions">
        <button type="button" className="ow-btn ow-btn--primary" onClick={copy}>
          <RepIcon name={copied ? 'check' : 'copy'} size={18} />{copied ? 'Copied' : 'Copy link'}
        </button>
        <button type="button" className="ow-btn ow-btn--line" onClick={download}><RepIcon name="download" size={18} />QR image</button>
        {canShare && (
          <button type="button" className="ow-btn ow-btn--line" onClick={() => navigator.share({ title: 'My ProPage', url }).catch(() => {})}>
            <RepIcon name="share" size={18} />Share
          </button>
        )}
      </div>
    </div>
  );
}

function ThemePanel({ current, onSelect }) {
  return (
    <div className="ow-panel">
      <h2 className="ow-panel-title">Theme</h2>
      <span className="ow-hint" style={{ marginTop: -8 }}>Changes your page right away.</span>
      <div className="ow-themes" role="radiogroup" aria-label="Theme">
        {Object.entries(THEMES).map(([key, t]) => (
          <ThemeCard key={key} id={key} theme={t} checked={current === key} onSelect={onSelect} name="page-theme" />
        ))}
      </div>
    </div>
  );
}

// ── Menu (fab when viewing, top bar when editing) ────────────────────────────

export function OwnerBar({ slug, editMode, onToggleEdit, canUndo, onUndo, currentTheme, onThemeSelect }) {
  const [open, setOpen] = useState(false);
  const [panel, setPanel] = useState(null);
  const ref = useRef(null);
  const close = () => { setOpen(false); setPanel(null); };
  useOutside(ref, open, close);

  const menu = open && (
    <div className="ow-menu" role="dialog" aria-label="Page menu">
      {panel && (
        <button type="button" className="ow-menu-item" onClick={() => setPanel(null)}><RepIcon name="arrowLeft" size={20} />Back</button>
      )}
      {panel === 'share' && <SharePanel slug={slug} />}
      {panel === 'theme' && <ThemePanel current={currentTheme} onSelect={onThemeSelect} />}
      {!panel && (
        <>
          {!editMode && (
            <button type="button" className="ow-menu-item" onClick={() => { onToggleEdit(); close(); }}>
              <RepIcon name="edit" size={20} /><span>Edit page<small>Change your words, links and blocks</small></span>
            </button>
          )}
          <button type="button" className="ow-menu-item" onClick={() => setPanel('share')}>
            <RepIcon name="qr" size={20} /><span>Share &amp; QR code<small>Link, printable QR, share sheet</small></span>
          </button>
          <button type="button" className="ow-menu-item" onClick={() => setPanel('theme')}>
            <RepIcon name="palette" size={20} /><span>Theme<small>{THEMES[currentTheme]?.label || 'Slate'}</small></span>
          </button>
          <div className="ow-menu-sep" />
          <Link className="ow-menu-item" href="/dashboard"><RepIcon name="inbox" size={20} />My leads</Link>
          <button type="button" className="ow-menu-item" onClick={() => supabase.auth.signOut().then(() => { window.location.href = '/'; })}>
            <RepIcon name="logout" size={20} />Sign out
          </button>
        </>
      )}
    </div>
  );

  if (editMode) {
    return (
      <div ref={ref} className="ow ow-editing">
        <div className="ow-top">
          <span className="ow-top-title">Editing your page<small>Each block saves on its own</small></span>
          <button type="button" className="ow-iconbtn" onClick={onUndo} disabled={!canUndo} aria-label="Undo last change" title="Undo last change"><RepIcon name="undo" size={20} /></button>
          <button type="button" className="ow-iconbtn" onClick={() => { setOpen(o => !o); setPanel(null); }} aria-expanded={open} aria-label="Page menu"><RepIcon name={open ? 'close' : 'menu'} size={20} /></button>
          <button type="button" className="ow-btn ow-btn--primary" onClick={onToggleEdit}>Done</button>
        </div>
        {menu}
      </div>
    );
  }

  return (
    <div ref={ref} className="ow">
      <button type="button" className="ow-fab" onClick={() => { setOpen(o => !o); setPanel(null); }} aria-expanded={open}>
        <RepIcon name={open ? 'close' : 'menu'} size={20} />My page
      </button>
      {menu}
    </div>
  );
}

